"""Build every sound, the sound bank and the loudness report (docs/audio/pipeline-handoff.md).

    uv run tools/audio/export.py                       # every sound
    uv run tools/audio/export.py --only step_          # write only names starting so
    uv run tools/audio/export.py --check               # write nothing; fail if a file is stale
    uv run tools/audio/export.py --sheet DIR           # also write a listening sheet DIR/index.html

Outputs (mono 16-bit 44.1 kHz WAV, loops with a smpl chunk):
    assets/audio/<family>/<name>.wav
    data/audio/sound_bank.tres                  (event id -> stream, bus, volume_db, pitch, loop)
    production/qa/evidence/audio/loudness.md    (measured loudness of every file; stinger vs bed, SE-8 AC-2)
Everything is deterministic (seeded per sound), so a re-export that changed nothing changes no file.
"""
import argparse
import importlib
import sys
from dataclasses import replace
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import picks  # noqa: E402
from lib import master  # noqa: E402
from sounds._legacy import legacy  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
BANK = ROOT / "data/audio/sound_bank.tres"
REPORT = ROOT / "production/qa/evidence/audio/loudness.md"
FAMILY_MODULES = ["steps", "ambience", "cues", "world", "voices", "scares", "ui"]
GAIT_DB = {"walk": 0.0, "sprint": 4.0, "crouch": -8.0, "crawl": -9.0}
# zone -> footstep surface (level doc: A labs tile, B server rooms metal grate, C security and links concrete)
SURFACE_OF_ZONE = {"A": "tile", "B": "metal", "C": "concrete", "link": "concrete"}
RANDOM_PITCH = 1.02  # AudioStreamRandomizer spread of a sound with variants (survivor sets are 6 % apart)
STINGER_GAIN_DB = 6.0  # data/knobs/scare.tres stinger_max_db_rel


def shipped(name, cands, mod):
    """The option picks.SHIP names for `name` (A when unlisted; D-F are the module's ROUND2), under the shipped name and events."""
    a, pick = cands[0], picks.SHIP.get(name, "A")
    if pick == "before":
        return replace(a, build=legacy(a.family, name, a.ids, a.loop).build, level=None, variants=1)
    c = dict(zip("ABCDEF", list(cands) + list(getattr(mod, "ROUND2", {}).get(name, []))))[pick]
    return replace(c, name=name, ids=a.ids, heard_as=c.name)


def all_sounds():
    out = []
    for m in FAMILY_MODULES:
        mod = importlib.import_module("sounds." + m)
        out += [shipped(n, c, mod) for n, c in mod.CANDIDATES.items()]
    names = [s.name for s in out]
    assert len(names) == len(set(names)), "duplicate sound names"
    return out


def bank_tres(takes):
    ext = ['[ext_resource type="Script" path="res://src/core/audio/sound_bank.gd" id="1"]',
           '[ext_resource type="Script" path="res://src/core/audio/sound_bank_entry.gd" id="2"]']
    pools, subs, entries = [], [], []  # a sound with variants plays through one shared AudioStreamRandomizer
    groups = {}
    for t in takes:
        groups.setdefault(t.sound.name, []).append(t)
    for i, ts in enumerate(groups.values()):
        s = ts[0].sound
        for t in ts:
            ext.append('[ext_resource type="AudioStream" path="res://%s" id="s%d_%d"]' % (t.path(), i, t.variant))
        ref = 'ExtResource("s%d_0")' % i
        if len(ts) > 1:
            streams = "\n".join('stream_%d/stream = ExtResource("s%d_%d")\nstream_%d/weight = 1.0' % (t.variant, i, t.variant, t.variant)
                                for t in ts)
            pools.append('[sub_resource type="AudioStreamRandomizer" id="r%d"]\nrandom_pitch = %s\nstreams_count = %d\n%s\n'
                         % (i, repr(float(RANDOM_PITCH)), len(ts), streams))
            ref = 'SubResource("r%d")' % i
        bus = master.FAMILIES[s.family][1]
        for eid, vol, pitch in s.ids:
            sid = "e%d" % len(subs)
            subs.append('[sub_resource type="Resource" id="%s"]\nscript = ExtResource("2")\nstream = %s\n'
                        'bus = &"%s"\nvolume_db = %s\npitch_scale = %s\nloop = %s\n'
                        % (sid, ref, bus, repr(float(vol)), repr(float(pitch)), "true" if s.loop else "false"))
            entries.append('&"%s": SubResource("%s")' % (eid, sid))
    subs = pools + subs
    gait = ", ".join('&"%s": %s' % (g, repr(float(d))) for g, d in GAIT_DB.items())
    zones = ", ".join('&"%s": &"%s"' % kv for kv in SURFACE_OF_ZONE.items())
    head = ('[gd_resource type="Resource" script_class="SoundBank" load_steps=%d format=3]\n\n'
            '; GENERATED by tools/audio/export.py; edit the sounds, not this file.\n\n' % (len(ext) + len(subs) + 1))
    body = ('[resource]\nscript = ExtResource("1")\nentries = Dictionary[StringName, Resource]({\n%s\n})\n'
            'suffix_db = Dictionary[StringName, float]({%s})\n'
            'surface_of_zone = Dictionary[StringName, StringName]({%s})\n'
            'default_surface = &"concrete"\n' % (",\n".join(entries), gait, zones))
    return head + "\n".join(ext) + "\n\n" + "\n".join(subs) + "\n" + body


def report_md(takes):
    st = next(t for t in takes if t.sound.family == "stinger")
    beds = [t for t in takes if t.sound.family == "ambience"]
    lines = ["# Audio loudness", "",
             "Generated by `tools/audio/export.py` (BS.1770 K-weighted momentary loudness over the loudest 400 ms, mono "
             "44.1 kHz, measured on the file as built). Targets are inference (no GDD number); see `lib/master.py` "
             "FAMILIES. A `legacy` row is a placeholder shipped as built: its target column is its own measurement.", "",
             "## Stinger vs zone bed (scare-events rule 26, SE-8 AC-2: at most +6 dB)", "",
             "Stinger playback gain = `stinger_max_db_rel` %.1f dB (data/knobs/scare.tres), both at bus 0 dB." % STINGER_GAIN_DB, "",
             "| Bed | Bed LUFS | Stinger file LUFS | Stinger as played | Over bed | Within +6 dB |", "|---|---|---|---|---|---|"]
    for b in beds:
        over = st.lufs + STINGER_GAIN_DB - b.lufs
        lines.append("| %s | %.1f | %.1f | %.1f | %+.1f dB | %s |" % (
            b.sound.file(), b.lufs, st.lufs, st.lufs + STINGER_GAIN_DB, over, "yes" if over <= 6.0 else "NO"))
    lines += ["", "## Every file", "", "| File | Category | Bus | Target LUFS | Measured LUFS | Peak dBFS | Seconds |",
              "|---|---|---|---|---|---|---|"]
    for t in takes:
        s = t.sound
        target = s.level if s.level is not None else round(t.lufs, 1)
        lines.append("| `%s` | %s | %s | %.1f | %.1f | %.1f | %.2f |" % (
            t.path(), s.family, master.FAMILIES[s.family][1], target, t.lufs, t.peak_db, len(t.x) / 44100))
        if s.level is not None and t.limited:
            print("peak-limited: %s short of %.1f" % (s.name, s.level))
    return "\n".join(lines) + "\n"


def same_pcm(a, b):
    """Within one 16-bit step in at most one sample in a thousand (numpy/scipy wheels round differently per OS)."""
    x, y = master.pcm(a), master.pcm(b)
    return len(x) == len(y) and np.mean(np.abs(x.astype(int) - y.astype(int)) > 1) == 0 and np.mean(x != y) <= 0.001


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="", help="write only sounds whose name starts with this")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if a file differs from what the code makes")
    ap.add_argument("--sheet", metavar="DIR", help="write a listening sheet DIR/index.html")
    args = ap.parse_args()
    takes = [master.render(s, v) for s in all_sounds() for v in range(s.variants)]
    for t in takes:
        if t.sound.level is not None and t.limited:
            print("peak-limited: %s" % t.sound.name)
    files = {ROOT / t.path(): master.wav_bytes(t.x, t.sound.loop) for t in takes}
    texts = {BANK: bank_tres(takes), REPORT: report_md(takes)}
    stale = [p for p in (ROOT / "assets/audio").rglob("*") if p.suffix in (".wav", ".ogg") and p not in files]
    if args.check:
        bad = [str(p.relative_to(ROOT)) for p, d in files.items() if not p.exists() or not same_pcm(p.read_bytes(), d)]
        bad += [str(p.relative_to(ROOT)) for p, s in texts.items() if not p.exists() or p.read_text(encoding="utf-8") != s]
        bad += ["stale " + str(p.relative_to(ROOT)) for p in stale]
        print("\n".join(bad) if bad else "audio up to date")
        sys.exit(1 if bad else 0)
    for p, d in files.items():
        if p.name.startswith(args.only) and not (p.exists() and p.read_bytes() == d):
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(d)
    if not args.only:
        for p, s in texts.items():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(s, encoding="utf-8", newline="\n")
        for p in stale:
            p.unlink()
            Path(str(p) + ".import").unlink(missing_ok=True)
    for t in takes:
        if t.sound.name.startswith(args.only):
            print("%-24s %6.1f LUFS %6.1f dBFS %6.2f s" % (t.sound.name, t.lufs, t.peak_db, len(t.x) / 44100))
    if args.sheet:
        from lib import page
        page.sheet(Path(args.sheet), [t for t in takes if t.sound.name.startswith(args.only)])


if __name__ == "__main__":
    main()
